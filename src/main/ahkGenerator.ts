import type { Macro, MouseStep, Profile } from '../shared/types'
import { isValidKey } from '../shared/types'
import { isMouseKey, splitMods } from '../shared/keys'

/** Escape a value for use inside an AHK v1 expression string literal. */
const q = (s: string) => '"' + s.replace(/`/g, '``').replace(/"/g, '""') + '"'

/** Strip anything that could break out of a `; comment` line. */
const comment = (s: string) => s.replace(/[\r\n]/g, ' ')

/**
 * ["2","8","z"] -> "{Blind}{2}{8}{z}".
 *
 * {Blind} stops ControlSend from briefly releasing modifiers you are physically holding
 * (Ctrl/Alt/Shift) — without it a running loop breaks your own Ctrl+N / Alt+N skills.
 * Keys that carry their own modifiers (e.g. "+1") are sent without {Blind} so the
 * modifier is applied correctly.
 */
export function renderKeys(keys: string[]): string {
  const valid = keys.filter(isValidKey)
  if (valid.length === 0) return ''
  const hasMods = valid.some((k) => splitMods(k).mods !== '')
  const body = valid
    .map((k) => {
      const { mods, key } = splitMods(k)
      return mods + '{' + key + '}'
    })
    .join('')
  return (hasMods ? '' : '{Blind}') + body
}

/** Build unique, AHK-safe variable names per window: "Templar" -> PID_Templar. */
export function windowVarNames(profile: Profile): Map<string, string> {
  const used = new Set<string>()
  const out = new Map<string, string>()
  for (const w of profile.windows) {
    const base = 'PID_' + (w.name.replace(/[^A-Za-z0-9_]/g, '_').replace(/_+/g, '_').replace(/^_|_$/g, '') || 'Window')
    let name = base
    for (let n = 2; used.has(name.toLowerCase()); n++) name = `${base}_${n}`
    used.add(name.toLowerCase())
    out.set(w.id, name)
  }
  return out
}

/** Hotkey string for the Hotkey command: "~$+F1", "$Tab", "XButton1". */
export function hotkeyName(m: Pick<Macro, 'hotkey' | 'passThrough'>): string {
  return (m.passThrough ? '~' : '') + (isMouseKey(m.hotkey) ? '' : '$') + m.hotkey
}

export function activeMacros(profile: Profile): Macro[] {
  const seen = new Set<string>()
  return profile.macros.filter((m) => {
    if (!m.enabled || !isValidKey(m.hotkey)) return false
    const k = m.hotkey.toLowerCase()
    if (seen.has(k) || (profile.suspendKey && profile.suspendKey.toLowerCase() === k)) return false
    seen.add(k)
    return true
  })
}

const BTN = { L: 'Left', R: 'Right', M: 'Middle' } as const

/** AHK lines that play back mouse steps, checking `abort` between steps. */
function mouseLines(steps: MouseStep[], speed: number, abort: string): string[] {
  const out: string[] = []
  for (const s of steps) {
    const delay = Math.round(s.delayMs / speed)
    if (delay > 0) {
      out.push(`Sleep, ${delay}`)
      out.push(`if (${abort})`, '    return')
    }
    const xy = `${Math.round(s.x)}, ${Math.round(s.y)}`
    if (s.type === 'move') out.push(`MouseMove, ${xy}, 0`)
    else if (s.type === 'click') out.push(`Click, ${xy}, ${BTN[s.button]}, ${s.count === 2 ? 2 : 1}`)
    else out.push(`Click, ${xy}, ${BTN[s.button]}, ${s.type === 'down' ? 'Down' : 'Up'}`)
  }
  return out
}

export interface GenerateOptions {
  /** Start with macros live (true) or waiting for the start/stop key / button (false). */
  running: boolean
}

export function generateScript(profile: Profile, opts: GenerateOptions = { running: true }): string {
  const vars = windowVarNames(profile)
  const macros = activeMacros(profile)
  const L: string[] = []
  const push = (...lines: string[]) => L.push(...lines)

  push(
    '; ==========================================================',
    `; Generated by BINDit - profile: ${comment(profile.name)}`,
    '; Do not edit: this file is regenerated every time the engine starts.',
    '; ==========================================================',
    '#NoEnv',
    '#SingleInstance Force',
    '#Persistent',
    '#UseHook On',
    '#MaxHotkeysPerInterval 500',
    'DetectHiddenWindows, On',
    'CoordMode, Mouse, Screen',
    'SetMouseDelay, -1',
    'SetDefaultMouseSpeed, 0',
    `Menu, Tray, Tip, % ${q('BINDit - ' + profile.name.slice(0, 100))}`,
    '',
    '; --- Windows (ahk_pid per account) ---'
  )
  for (const w of profile.windows) {
    push(`${vars.get(w.id)} := ${w.pid && w.pid > 0 ? w.pid : 0}  ; ${comment(w.name)}`)
  }
  push('')
  push('; --- Macro states ---')
  macros.forEach((m, i) => m.type === 'toggle' && push(`M${i}_On := false`))
  push('')
  push('; --- Hotkeys ---')
  // Toggles get 2 threads so a second press can switch them off mid-run.
  macros.forEach((m, i) => push(`Hotkey, % ${q(hotkeyName(m))}, M${i}_Down${m.type === 'toggle' ? ', T2' : ''}  ; ${comment(m.name)}`))
  if (profile.suspendKey && isValidKey(profile.suspendKey)) {
    const sk = (isMouseKey(profile.suspendKey) ? '' : '$') + profile.suspendKey
    push(`Hotkey, % ${q(sk)}, FB_StartStop  ; start / stop all macros`)
  }
  if (opts.running) {
    push('FB_Out("RUNNING")')
  } else {
    push('Suspend, On', 'FB_Out("STOPPED")')
  }
  push('return', '')

  push(
    'FB_Out(msg) {',
    '    FileAppend, %msg%`n, *',
    '}',
    '',
    'SendTo(pid, keys) {',
    '    if (pid && WinExist("ahk_pid " pid))',
    '        ControlSend, , %keys%, ahk_pid %pid%',
    '}',
    ''
  )

  push('FB_StartStop:', 'Suspend, Toggle', 'if (A_IsSuspended) {')
  macros.forEach((m, i) => {
    if (m.type === 'toggle') push(`    M${i}_On := false`, `    SetTimer, M${i}_Run, Off`)
  })
  push(
    '    TrayTip, BINDit, Macros stopped, 1',
    '    FB_Out("STOPPED")',
    '} else {',
    '    TrayTip, BINDit, Macros started, 1',
    '    FB_Out("RUNNING")',
    '}',
    'return',
    ''
  )

  macros.forEach((m, i) => {
    const baseKey = splitMods(m.hotkey).key
    push(`; ---- [${i}] ${comment(m.name)} (${m.kind}, ${m.type}) ----`)
    push(`M${i}_Run:`)
    if (m.kind === 'mouse') {
      const steps = m.mouse.steps
      // Stop mid-path when stopped, toggled off or (hold) released.
      const abort =
        m.type === 'toggle'
          ? `A_IsSuspended || !M${i}_On`
          : m.type === 'hold'
            ? `A_IsSuspended || !GetKeyState(${q(baseKey)}, "P")`
            : 'A_IsSuspended'
      if (steps.length) {
        if (m.mouse.restoreCursor) push(`MouseGetPos, M${i}_X, M${i}_Y`)
        const speed = m.mouse.mode === 'recorded' ? m.mouse.speed : 1
        // On abort the label returns early; restore the cursor via a wrapper label.
        push(`Gosub, M${i}_Path`)
        // If the path was cut short between a press and its release, let go of the button.
        for (const b of ['L', 'R', 'M'] as const) {
          if (steps.some((s) => s.type === 'down' && s.button === b)) {
            push(`if GetKeyState("${BTN[b].charAt(0)}Button")`, `    Click, ${BTN[b]}, Up`)
          }
        }
        if (m.mouse.restoreCursor) push(`MouseMove, %M${i}_X%, %M${i}_Y%, 0`)
        push('return', '')
        push(`M${i}_Path:`)
        push(...mouseLines(steps, speed, abort))
      }
    } else {
      push(`SetKeyDelay, ${Math.round(m.keyDelayMs)}`)
      for (const a of m.actions) {
        const v = vars.get(a.windowId)
        const keys = renderKeys(a.keys)
        if (v && keys) push(`SendTo(${v}, ${q(keys)})`)
      }
    }
    push('return', '')
    push(`M${i}_Down:`)
    if (m.type === 'once') {
      push(`Gosub, M${i}_Run`)
    } else if (m.type === 'hold') {
      push(
        'Loop {',
        `    Gosub, M${i}_Run`,
        `    Sleep, ${Math.round(m.loopIntervalMs)}`,
        `    if (A_IsSuspended || !GetKeyState(${q(baseKey)}, "P"))`,
        '        break',
        '}'
      )
    } else {
      push(
        `M${i}_On := !M${i}_On`,
        `if (M${i}_On) {`,
        `    Gosub, M${i}_Run`,
        `    if (M${i}_On)`,
        `        SetTimer, M${i}_Run, ${Math.round(m.loopIntervalMs)}`,
        '} else {',
        `    SetTimer, M${i}_Run, Off`,
        '}'
      )
    }
    push('return', '')
  })

  return L.join('\r\n')
}
